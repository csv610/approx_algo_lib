    print(f"  Step 3: GCD({12}, {6}) = {euclid_gcd(48, 18)}")

    # --- 2D lattice: Gauss' algorithm ---
    print("\n--- 2. Gauss' 2D Algorithm ---")
    b1 = [1.0, 1.0]
    b2 = [1.0, -1.0]
    print(f"  Basis: b1 = {b1}, b2 = {b2}")
    shortest = gauss_2d(b1, b2)
    print(f"  Shortest vector: {shortest}, length = {vec_norm(shortest):.4f}")

