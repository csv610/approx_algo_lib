    b2 = [1.0, 2.0]
    print(f"\n  Basis: b1 = {b1}, b2 = {b2}")
    shortest = gauss_2d(b1, b2)
    print(f"  Shortest vector: {shortest}, length = {vec_norm(shortest):.4f}")

